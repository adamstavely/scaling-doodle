// Design tokens: Energy Studio's DTCG file -> CSS custom properties, checked against Trench Coat's DTCG files.
//
//   node scripts/tokens.mjs          write src/styles/tokens.css
//   node scripts/tokens.mjs --check  fail if src/styles/tokens.css is out of date
//
// Aliases like {tc.space.4} point at Trench Coat's DTCG tokens (primitives + Clean light). They are written as
// var(--tc-space-4), so Trench Coat's light/dark and look switching keep working at runtime. Literal values are
// written as plain CSS. Also exported for scripts/check-styles.mjs: the set of token names a stylesheet may use.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const require = createRequire(import.meta.url);
const SOURCE = join(root, 'tokens/energy-studio.tokens.json');
const OUTPUT = join(root, 'src/styles/tokens.css');
const TC_SETS = ['primitives', 'clean-light', 'clean-dark', 'standard-light', 'standard-dark'];

const isToken = (v) => v && typeof v === 'object' && '$value' in v;

/** Walk a DTCG tree: yields [path, token, inheritedType]. A group's own token sits under "$root". */
function* walk(node, path = [], type) {
  const groupType = node.$type ?? type;
  for (const [key, value] of Object.entries(node)) {
    if (key === '$root' && isToken(value)) yield [path, value, value.$type ?? groupType];
    if (key.startsWith('$') || !value || typeof value !== 'object') continue;
    if (isToken(value)) yield [[...path, key], value, value.$type ?? groupType];
    else yield* walk(value, [...path, key], groupType);
  }
}

/** Trench Coat's DTCG tokens: "tc.<path>" -> its CSS custom property. */
export function trenchCoatTokens() {
  const byPath = new Map();
  for (const set of TC_SETS) {
    const tree = require(`@adamstavely/trenchcoat/tokens/dtcg/${set}.json`);
    for (const [path, token] of walk(tree)) {
      const css = token.$extensions?.['com.trenchcoat']?.css;
      if (css) byPath.set(['tc', ...path].join('.'), css);
    }
  }
  return byPath;
}

function cssValue(value, type, name) {
  if (typeof value === 'number') return String(value);
  if (typeof value === 'string') return value;
  if (type === 'dimension' || type === 'duration') {
    if (typeof value?.value !== 'number' || !value.unit) throw new Error(`${name}: ${type} needs { value, unit }`);
    return `${value.value}${value.unit}`;
  }
  if (type === 'color' && value?.hex) return value.alpha === undefined ? value.hex : `color-mix(in srgb, ${value.hex} ${value.alpha * 100}%, transparent)`;
  if (type === 'fontFamily' && Array.isArray(value)) return value.map((f) => (/\s/.test(f) ? `"${f}"` : f)).join(', ');
  if (type === 'cubicBezier' && Array.isArray(value)) return `cubic-bezier(${value.join(', ')})`;
  throw new Error(`${name}: can't write a ${type} value ${JSON.stringify(value)} as CSS; alias a Trench Coat token instead`);
}

/** Energy Studio's tokens as [cssName, cssValue, description]. */
export function energyStudioTokens() {
  const tc = trenchCoatTokens();
  const tree = JSON.parse(readFileSync(SOURCE, 'utf8'));
  const out = [];
  for (const [path, token, type] of walk(tree)) {
    if (path[0] !== 'es') throw new Error(`${path.join('.')}: Energy Studio tokens live under "es"`);
    const name = `--${path.join('-')}`;
    if (!type) throw new Error(`${name}: no $type on the token or its group`);
    const alias = typeof token.$value === 'string' && token.$value.match(/^\{(.+)\}$/);
    let value;
    if (alias) {
      const target = alias[1];
      if (target.startsWith('tc.')) {
        const css = tc.get(target);
        if (!css) throw new Error(`${name}: ${token.$value} is not a Trench Coat DTCG token`);
        value = `var(${css})`;
      } else {
        value = `var(--${target.replace(/\./g, '-')})`;
      }
    } else {
      value = cssValue(token.$value, type, name);
    }
    out.push([name, value, token.$description]);
  }
  return out;
}

function render() {
  const lines = energyStudioTokens().map(([name, value, desc]) => `  ${name}: ${value};${desc ? ` /* ${desc} */` : ''}`);
  return [
    '/* Generated by scripts/tokens.mjs from tokens/energy-studio.tokens.json. Do not edit: change the JSON and run',
    ' * `npm run tokens -w @energy-studio/web`. */',
    ':root {',
    ...lines,
    '}',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const css = render();
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(OUTPUT, 'utf8');
    } catch {}
    if (current !== css) {
      console.error('src/styles/tokens.css is out of date: run `npm run tokens -w @energy-studio/web`.');
      process.exit(1);
    }
    console.log('Design tokens are up to date.');
  } else {
    writeFileSync(OUTPUT, css);
    console.log(`Wrote ${OUTPUT}`);
  }
}
